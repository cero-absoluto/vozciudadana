// evidentialScope.js
// ---------------------------------------------------------------------------
// Deterministic "Statement of Evidential Scope" for a Voice Protest report.
//
// Produces, for any convocatoria, three fixed sections:
//   1. demonstrates          — what the report DOES establish (affirmative, leads)
//   2. outside_scope          — outside the report's scope (kept short: affiliation, truth, representativeness)
//   3. methods               — the verification methods actually used
// plus:
//   participation_rate       — ONLY when the system owns the universe (census). Never estimated.
//   admission_rules          — the public rules the convocatoria passed to be admitted.
//
// Design constraints (from the audit conversation):
//   - Autogenerated and DETERMINISTIC. Never author-written. It is a function of
//     the data (scope, dominio_email, requiere_censo, local_verified), exactly as
//     auditable as the integrity hash.
//   - "Evidence quality, not legitimacy": describes the strength of available
//     verification SIGNALS, never a hierarchy of participants.
//   - Affirmative first; the "outside scope" list is deliberately short.
//   - Output is i18n keys + params. The frontend renders them in NEUTRAL
//     typography — no checks/crosses, stars, or colour grading (those re-create a
//     pass/fail hierarchy). Icons are a rendering choice the report must avoid.
//
// Returns plain data; the caller adds it to the /informe response as
// `evidential_scope` and the report renders it via i18n.
// ---------------------------------------------------------------------------

/** Resolve the verification mode from the protest row. */
function modeOf(protest) {
  if (protest.dominio_email) {
    return protest.requiere_censo ? 'institutional_census' : 'institutional_email';
  }
  // geographic scopes
  return protest.scope; // 'national' | 'regional' | 'local' | 'global'
}

/**
 * @param {object} protest  full protests row (scope, dominio_email, requiere_censo,
 *                          country_name, convocatoria_osm_id, convocatoria_ciudad_nombre,
 *                          target_wikidata_id, tipo_abuso, fuente_url ...)
 * @param {object} agg      aggregates already computed by /informe:
 *                          { total, desglose_geografico_local, paises_distintos,
 *                            census_eligible? }
 * @returns {object} evidential_scope
 */
export function buildEvidentialScope(protest, agg = {}) {
  const mode = modeOf(protest);
  if (!agg.recorded_methods) return {mode,version:2,recorded_methods:null,
    demonstrates:[{key:'demonstrates.evidence_unavailable',params:{}}],outside_scope:[],methods:[],participation_rate:null,admission_rules:[]};
  const total = agg.total ?? protest.count ?? 0;
  const dgl = agg.desglose_geografico_local || null;
  const localVerified = dgl?.local_verified?.count ?? 0;
  const territory = protest.convocatoria_ciudad_nombre || protest.country_name || null;

  const demonstrates = [];
  const outside_scope = [];   // framed as methodological delimitation, not a deficiency
  const methods = [];

  // ── "unique participation" line (identifier-specific key for clean i18n) ──
  demonstrates.push({
    key: protest.dominio_email
      ? 'demonstrates.unique_participation_email'
      : 'demonstrates.unique_participation_phone',
    params: {},
  });

  // ── mode-specific demonstrable + affiliation caveat + methods ────────────
  switch (mode) {
    case 'national':
      demonstrates.push({ key: 'demonstrates.sim_country', params: { country: protest.country_name } });
      outside_scope.push({ key: 'not.affiliation_geographic', params: {} });
      methods.push({ key: 'methods.sms_otp' });
      methods.push({ key: 'methods.sim_country' });
      methods.push({ key: 'methods.ip' });
      break;

    case 'regional':
      // Honesty: regional is a creator DECLARATION, not a technical restriction —
      // unless an OSM entity + GPS verified some adhesions territorially.
      if (dgl && localVerified > 0) {
        demonstrates.push({ key: 'demonstrates.local_verified_region', params: { count: localVerified, total: dgl.total ?? total, territory } });
        methods.push({ key: 'methods.gps_osm_region', params: { territory } });
      }
      outside_scope.push({ key: 'not.region_presence', params: { territory } });
      methods.unshift({ key: 'methods.sms_otp' });
      methods.push({ key: 'methods.ip' });
      break;

    case 'local':
      if (dgl && localVerified > 0) {
        demonstrates.push({ key: 'demonstrates.local_verified_municipality', params: { count: localVerified, total: dgl.total ?? total, territory } });
        methods.push({ key: 'methods.gps_osm_municipality', params: { territory } });
      }
      outside_scope.push({ key: 'not.residence', params: { territory } });
      methods.unshift({ key: 'methods.sms_otp' });
      methods.push({ key: 'methods.ip' });
      break;

    case 'global':
      demonstrates.push({ key: 'demonstrates.country_breakdown', params: {} });
      outside_scope.push({ key: 'not.affiliation_geographic', params: {} });
      methods.push({ key: 'methods.sms_otp' });
      methods.push({ key: 'methods.ip' });
      break;

    case 'institutional_email':
      demonstrates.push({ key: 'demonstrates.institutional_affiliation', params: { domain: protest.dominio_email } });
      outside_scope.push({ key: 'not.institutional_role', params: {} });
      methods.push({ key: 'methods.email_otp', params: { domain: protest.dominio_email } });
      break;

    case 'institutional_census':
      demonstrates.push({ key: 'demonstrates.institutional_affiliation', params: { domain: protest.dominio_email } });
      demonstrates.push({ key: 'demonstrates.census_vouching', params: {} });
      outside_scope.push({ key: 'not.institutional_role', params: {} });
      methods.push({ key: 'methods.email_otp', params: { domain: protest.dominio_email } });
      methods.push({ key: 'methods.census_vouching' });
      break;
  }

  // New report path supplies observed rows; old callers remain compatible.
  if (agg.recorded_methods) {
    const observed=agg.recorded_methods;
    const allowed=new Set(['phone_otp','institutional_email_otp','qr','eid','unknown']);
    methods.splice(0,methods.length);
    for(const [method,count] of Object.entries(observed.counts)) {
      if(allowed.has(method) && count>0) methods.push({key:'methods.recorded_'+method,params:{count}});
    }
    if(observed.gps>0)methods.push({key:'methods.recorded_gps',params:{count:observed.gps}});
    if(observed.ip>0)methods.push({key:'methods.recorded_ip',params:{count:observed.ip}});
    for(let i=demonstrates.length-1;i>=0;i--) {
      const key=demonstrates[i].key;
      if(['demonstrates.unique_participation_phone','demonstrates.unique_participation_email','demonstrates.institutional_affiliation','demonstrates.census_vouching','demonstrates.sim_country','demonstrates.country_breakdown'].includes(key))demonstrates.splice(i,1);
    }
    demonstrates.unshift({key:'demonstrates.recorded_identifiers',params:{total:observed.total}});
    outside_scope.push({key:'not.device_credential_scope',params:{}});
    if(protest.dominio_email)outside_scope.push({key:'not.domain_scope',params:{}});
    if(protest.requiere_censo)outside_scope.push({key:'not.census_scope',params:{}});
    if(protest.dominio_email)outside_scope.push({key:'not.institutional_expiry_scope',params:{}});
  }

  // ── core "outside scope" lines, always present (kept short) ──────────────
  outside_scope.push({ key: 'not.truth', params: {} });
  outside_scope.push({ key: 'not.representative', params: {} });

  // ── public auditability is always demonstrable ───────────────────────────
  if (!agg.recorded_methods || protest.hash_integridad) demonstrates.push({ key: 'demonstrates.public_auditability', params: {} });

  // ── participation rate: ONLY when the universe is owned by the system ─────
  // Census defines a registered member set. Email-domain mode does NOT (the
  // platform cannot know how many @domain addresses exist). Never estimate.
  let participation_rate = null;
  if (mode === 'institutional_census' && Number.isInteger(agg.census_eligible) && agg.census_eligible > 0) {
    participation_rate = {
      eligible: agg.census_eligible,
      count: total,
      rate: Math.round((total / agg.census_eligible) * 1000) / 10, // one decimal, %
      source: 'registered_census',
    };
  }

  // ── admission rules applied (the public rules the convocatoria passed) ────
  const admission_rules = [];
  if (protest.target_wikidata_id) {
    admission_rules.push({ key: 'admission.public_institution', params: { wikidata: protest.target_wikidata_id } });
  }
  if (protest.tipo_abuso) {
    admission_rules.push({ key: 'admission.abuse_category', params: { category: protest.tipo_abuso } });
  }
  admission_rules.push({ key: 'admission.source_accepted', params: {} });
  admission_rules.push({ key: 'admission.petition_filter', params: {} });
  if (protest.target_wikidata_id) {
    admission_rules.push({ key: 'admission.wikidata_verified', params: {} });
  }

  return {
    mode,
    demonstrates,
    outside_scope,
    methods,
    participation_rate,
    admission_rules,
    // schema marker so the frontend/consumers know the contract version
    version: agg.recorded_methods ? 2 : 1,
    recorded_methods: agg.recorded_methods ?? null,
  };
}

