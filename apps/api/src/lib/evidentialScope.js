Object.assign(EVIDENTIAL_SCOPE_EN, Object.fromEntries(Object.entries(RECORDED_SCOPE_EN).map(([key,text]) => [key,(params={}) => text.replace(/\{(\w+)\}/g,(_,name) => String(params[name] ?? ''))])));

/** Render a scope object to plain English lines (reference / testing helper). */
export function renderStatementEn(scope) {
  const line = (item) => {
    const fn = EVIDENTIAL_SCOPE_EN[item.key];
    return fn ? fn(item.params || {}) : `[${item.key}]`;
  };
  return {
    'What this report demonstrates': scope.demonstrates.map(line),
    'Outside the scope of this report': scope.outside_scope.map(line),
    'Verification methods used': scope.methods.map(line),
    'Participation rate': scope.participation_rate
      ? [`${scope.participation_rate.count} of ${scope.participation_rate.eligible} registered (${scope.participation_rate.rate}%).`]
      : ['(not shown — no system-owned universe)'],
    'Admission rules applied': scope.admission_rules.map(line),
  };
}
